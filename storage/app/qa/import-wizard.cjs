    await dialog.locator('[name=service]').fill('Consulta externa');
    await page.screenshot({ path: 'storage/app/qa/expedient-step-3.png' });
    await next.click();
    await dialog.locator('[name=medication_name]').fill('Medicamento de ejemplo');
    await dialog.locator('[name=priority]').selectOption('Alta');
    await next.click();
    await dialog.locator('[data-expedient-files]').setInputFiles({ name: 'no-permitido.txt', mimeType: 'text/plain', buffer: Buffer.from('example') });
    assert((await dialog.locator('[data-wizard-feedback]').textContent()).includes('usa PDF'));
    await dialog.locator('[data-expedient-files]').setInputFiles({ name: 'receta_medica.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\n% demo preview only') });
    assert.equal(await dialog.locator('.ew-file').count(), 1);
    await page.screenshot({ path: 'storage/app/qa/expedient-step-5.png' });
    await next.click();
    await page.waitForFunction(() => document.querySelector('.expedient-wizard').getAttribute('aria-busy') === 'false');
    assert(await dialog.locator('[data-wizard-step="5"]').isVisible());
