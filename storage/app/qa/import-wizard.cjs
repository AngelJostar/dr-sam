    const dialog = page.locator('.expedient-wizard');
    const next = dialog.locator('[data-wizard-next]');
    await next.click();
    assert(await dialog.locator('[name=first_name]').evaluate(el => !el.validity.valid));
    await dialog.locator('[name=first_name]').fill('Andrea');
    await dialog.locator('[name=first_surname]').fill('Navarro');
    await dialog.locator('[name=second_surname]').fill('López');
    await dialog.locator('[name=birth_date]').fill('1988-03-14');
    await dialog.locator('[name=sex]').selectOption('Femenino');
    await page.screenshot({ path: 'storage/app/qa/expedient-step-1.png' });
    await next.click();
    await dialog.locator('[name=email]').fill('correo-invalido');
    await next.click();
    assert(await dialog.locator('[data-wizard-step="1"]').isVisible());
    await dialog.locator('[name=email]').fill('prueba@example.test');
    await next.click();
    await dialog.locator('[data-add-hospital]').click();
    await dialog.locator('[name=new_hospital_name]').fill('Hospital de ejemplo');
