const assert = require('node:assert/strict');
const {createRequire} = require('node:module');
const rr = createRequire('C:/Users/Guillermo/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/package.json');
const {chromium} = rr('playwright');
(async () => {
 const browser = await chromium.launch({channel:'msedge',headless:true});
 try {
  const page = await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8000/acceso');
  await page.locator('#demo-username').selectOption('paciente');
  await Promise.all([page.waitForURL('**/dashboard'),page.getByRole('button',{name:'Ingresar',exact:true}).click()]);
  await page.goto('http://127.0.0.1:8000/patient#home');
  await page.locator('.kp-stories').waitFor();
  await page.waitForFunction(()=>document.querySelectorAll('.kp-stories .has-unseen').length===3);
  await page.screenshot({path:'storage/app/qa/stories-new.png'});
  await page.getByRole('button',{name:'Mariana López: historia nueva',exact:true}).tap();
  await page.locator('.kp-story-viewer[open]').waitFor();
  await page.waitForFunction(()=>document.querySelector('.kp-story-viewer img.kp-story-photo')?.naturalWidth>0);
  await page.getByRole('button',{name:'Pausar historia',exact:true}).click();
  await page.screenshot({path:'storage/app/qa/story-viewer.png'});
  await page.getByRole('button',{name:'Cerrar historia',exact:true}).click();
  assert.equal(await page.locator('.kp-stories .has-unseen').count(),2);
  await page.getByRole('button',{name:'Carlos Méndez: sin historias',exact:true}).tap({force:true});
  assert.equal(await page.locator('.kp-story-viewer[open]').count(),0);
  await page.reload();
  await page.getByRole('button',{name:'Mariana López: historia vista',exact:true}).waitFor();
  assert.equal(await page.locator('.kp-stories .has-unseen').count(),2);
  await page.getByRole('button',{name:'Mariana López: historia vista',exact:true}).tap();
  await page.locator('.kp-story-viewer[open]').waitFor();
  await page.locator('.kp-story-next').tap();
  await page.getByRole('dialog',{name:'Historia de Diego Ramírez',exact:true}).waitFor();
  await page.getByRole('button',{name:'Cerrar historia',exact:true}).click();
  const originalAvatar = await page.locator('.kp-story-own .kp-story-avatar').innerHTML();
  const picker = page.waitForEvent('filechooser');
  await page.getByRole('button',{name:'Agregar tu historia',exact:true}).tap();
  await (await picker).setFiles('public/images/patient-export/9bfe0ef87111af6547ae.jpg');
  await page.getByRole('dialog',{name:'Publicar tu historia',exact:true}).waitFor();
  await page.screenshot({path:'storage/app/qa/story-compose.png'});
  await page.getByRole('button',{name:'Compartir historia',exact:true}).click();
  await page.getByRole('button',{name:'Ver tu historia',exact:true}).waitFor();
  assert.equal(await page.locator('.kp-story-own .kp-story-avatar').innerHTML(),originalAvatar);
  await page.getByRole('button',{name:'Ver tu historia',exact:true}).tap();
  await page.getByRole('button',{name:'Eliminar historia',exact:true}).click();
  await page.getByRole('button',{name:'Agregar tu historia',exact:true}).waitFor();
  assert.equal(await page.locator('.kp-story-own .kp-story-avatar').innerHTML(),originalAvatar);
  await page.screenshot({path:'storage/app/qa/stories-seen.png'});
  assert.deepEqual(errors,[]);
  console.log('PASS: mobile demo unseen/seen/reload, disabled empty profiles, viewer navigation, upload, unchanged avatar, deletion; no JS errors.');
 } finally {await browser.close();}
})().catch(e=>{console.error(e.message);process.exitCode=1;});
